def plugins_js(names, statuses=None):
    rows = []
    statuses = statuses or {}
    for name in names:
        rows.append(json.dumps({
            "name": name,
            "status": statuses.get(name, True),
            "description": f"desc {name}",
            "parameters": {"keep": name},
        }, ensure_ascii=False, separators=(",", ":")))
    return (
        "// Generated by RPG Maker.\n"
        "// Do not edit this file directly.\n"
        "var $plugins =\n"
        "[\n" + ",\n".join(rows) + "\n];\n"
    )


def apply_documented_paste(text: str, after: str, tail: str) -> str:
    """Notepad steps: comma after MEO_Util_Node, paste language, comma before ];, paste the last line."""
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines()
    meo = next(i for i, line in enumerate(lines) if "MEO_Util_Node" in line and "name" in line)
    if not lines[meo].rstrip().endswith(","):
        lines[meo] = lines[meo].rstrip() + ","
    lines[meo + 1:meo + 1] = after.splitlines()
    end = next(i for i, line in enumerate(lines) if line.strip().startswith("];"))
    previous = end - 1
    while previous >= 0 and not lines[previous].strip():
        previous -= 1
    if previous >= 0 and not lines[previous].rstrip().endswith(","):
        lines[previous] = lines[previous].rstrip() + ","
    lines[end:end] = tail.splitlines()
    body = newline.join(lines)
    if text.endswith(("\n", "\r\n")):
        body += newline
    return body


class InstallTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="ru-install-"))
        self._prev_log = os.environ.get("NP_INSTALL_LOG")
        os.environ["NP_INSTALL_LOG"] = str(self.tmp / "install-log.txt")

    def tearDown(self):
        if self._prev_log is None:
            os.environ.pop("NP_INSTALL_LOG", None)
        else:
            os.environ["NP_INSTALL_LOG"] = self._prev_log
        shutil.rmtree(self.tmp, ignore_errors=True)

    def make_game(self, folder: Path, names=None, text=None) -> Path:
        names = names or ["Community_Basic", "MEO_Util_Node", "YEP_ItemCore"]
        www = folder / "www"
        (www / "js").mkdir(parents=True)
        body = text if text is not None else plugins_js(names)
        (www / "js" / "plugins.js").write_text(body, encoding="utf-8")
        (www / "csv").mkdir()
        (www / "csv" / "sheet.csv").write_text("ENGLISH-ORIGINAL\n", encoding="utf-8")
        (www / "data").mkdir()
        (www / "data" / "System.json").write_text('{"gameTitle":"EN"}\n', encoding="utf-8")
        (www / "data" / "Actors.json").write_text("[]\n", encoding="utf-8")
        (www / "save").mkdir()
        (www / "save" / "file1.rpgsave").write_bytes(b"SAVE")
        (www / "img").mkdir()
        (www / "img" / "keep.png").write_bytes(b"PNG")
        (folder / "Game.exe").write_bytes(b"MZ")
        return www

    def assert_installed(self, www: Path):
        plugins = www / "js" / "plugins.js"
        text = plugins.read_text(encoding="utf-8-sig")
        names = patch_plugins_js.names_of(patch_plugins_js.parse_plugins(text))
        self.assertEqual(names[0], "Community_Basic")
        self.assertEqual(names[names.index("MEO_Util_Node") + 1], "NP_Language")
        self.assertEqual(names[-1], "NP_OptionsCategories")
        self.assertEqual(patch_plugins_js.order_errors(names), [])
        yep = next(obj for obj in patch_plugins_js.parse_plugins(text) if obj["name"] == "YEP_ItemCore")
        self.assertEqual(yep["parameters"]["keep"], "YEP_ItemCore")
        self.assertEqual((www / "save" / "file1.rpgsave").read_bytes(), b"SAVE")
        self.assertEqual((www / "data" / "Actors.json").read_text(encoding="utf-8"), "[]\n")
        self.assertEqual((www / "img" / "keep.png").read_bytes(), b"PNG")
        self.assertNotEqual((www / "csv" / "sheet.csv").read_text(encoding="utf-8"), "ENGLISH-ORIGINAL\n")
        self.assertIn("Уровень", (www / "data" / "System.json").read_text(encoding="utf-8"))
        self.assertIn("Раса", (www / "csv" / "status.csv").read_text(encoding="utf-8"))
        for rel in (
            "js/plugins/NP_Language.js",
            "js/plugins/NP_OptionsCategories.js",
            "lang/en/build_info.json",
            "csv/npc/npc_misc.csv",
            "data/System.json",
        ):
            src = ROOT / "www" / rel
            dst = www / rel
            self.assertEqual(dst.read_bytes(), src.read_bytes(), rel)
        log = (self.tmp / "install-log.txt").read_text(encoding="utf-8-sig")
        self.assertIn(install.SUCCESS_RU, log)
        self.assertIn(install.SUCCESS_EN, log)
        self.assertIn(str(www), log)

    def test_game_root_then_repeat_keeps_first_backup(self):
        game = self.tmp / "game"
        www = self.make_game(game)
        plugins = www / "js" / "plugins.js"
        original = plugins.read_bytes()
        self.assertEqual(install.main([str(game)]), 0)
        self.assert_installed(www)
        bak = plugins.with_suffix(plugins.suffix + ".bak")
        self.assertEqual(bak.read_bytes(), original)
        patched = plugins.read_bytes()
        self.assertNotEqual(patched, original)
        self.assertEqual(install.main([str(game)]), 0)
        self.assertEqual(plugins.read_bytes(), patched)
        self.assertEqual(bak.read_bytes(), original)
        self.assertEqual((game / "Game.exe").read_bytes(), b"MZ")

    def test_www_folder_and_plugins_js_path(self):
        game = self.tmp / "game"
        www = self.make_game(game)
        plugins = www / "js" / "plugins.js"
        self.assertEqual(install.resolve_www(str(game)), www.resolve())
        self.assertEqual(install.resolve_www(str(www)), www.resolve())
        self.assertEqual(install.resolve_www(str(plugins)), www.resolve())
        self.assertEqual(install.resolve_www(str(game / "Game.exe")), www.resolve())
        self.assertEqual(install.resolve_www('"' + str(www) + '"'), www.resolve())
        self.assertEqual(install.main([str(plugins)]), 0)
        self.assert_installed(www)

