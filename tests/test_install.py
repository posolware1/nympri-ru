    def test_player_zip_matches_repo_payload(self):
        zpath = ROOT / "NymPri_080j_RU_Language_Patch.zip"
        prefix = "NymPri_080j_RU_Language_Patch/"
        with zipfile.ZipFile(zpath) as zf:
            names = set(zf.namelist())
            self.assertIn(prefix + "install.bat", names)
            self.assertIn(prefix + "manual/HOW.txt", names)
            self.assertIn(prefix + "manual/КАК.txt", names)
            self.assertIn(prefix + "manual/paste-after-MEO_Util_Node.txt", names)
