    def test_manual_paste_matches_installer(self):
        after_path = ROOT / "manual" / "paste-after-MEO_Util_Node.txt"
        tail_path = ROOT / "manual" / "paste-at-end.txt"
        after = after_path.read_text(encoding="utf-8-sig")
        tail = tail_path.read_text(encoding="utf-8-sig")
        expect_after, expect_tail = patch_plugins_js.manual_paste_texts()
        self.assertEqual(after, expect_after)
        self.assertEqual(tail, expect_tail)
        self.assertTrue(after.strip().endswith(","))
        self.assertFalse(tail.strip().endswith(","))
        fragment = (ROOT / "plugins_fragment.txt").read_text(encoding="utf-8")
        self.assertIn(after.strip(), fragment)
        self.assertIn(tail.strip(), fragment)

        game = self.tmp / "game"
        www = self.make_game(game)
        original = (www / "js" / "plugins.js").read_text(encoding="utf-8")
        edited = apply_documented_paste(original, after, tail)
        (www / "js" / "plugins.js").write_text(edited, encoding="utf-8")
        other = self.tmp / "other"
        other.mkdir()
        shutil.copytree(www, other / "www")
        (other / "Game.exe").write_bytes(b"MZ")
        (other / "www" / "js" / "plugins.js").write_text(original, encoding="utf-8")
        self.assertEqual(install.main([str(other)]), 0)
        manual_entries = patch_plugins_js.parse_plugins(edited)
        installed_entries = patch_plugins_js.parse_plugins(
            (other / "www" / "js" / "plugins.js").read_text(encoding="utf-8")
        )
        self.assertEqual(
            patch_plugins_js.names_of(manual_entries),
            patch_plugins_js.names_of(installed_entries),
        )
        for left, right in zip(manual_entries, installed_entries):
            if str(left.get("name", "")).startswith("NP_"):
                self.assertEqual(left, right)

